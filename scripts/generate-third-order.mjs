import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { createServer } from 'vite'

const outputDirectory = path.resolve('docs/generated/third-order')
const runtimePath = path.resolve('src/features/third-order/data/generatedDefinitions.ts')
const server = await createServer({
  server: { middlewareMode: true, watch: null },
  appType: 'custom',
  logLevel: 'error',
})
try {
  const { generateThirdOrderDefinitions } = await server.ssrLoadModule(
    '/src/features/third-order/generator/generateDefinitions.ts',
  )
  const result = await generateThirdOrderDefinitions({ onProgress: console.log })
  const { compactThirdOrderDefinitions, serializeThirdOrderDefinitions } =
    await server.ssrLoadModule('/src/features/third-order/generator/compactDefinitions.ts')
  const runtimeDefinitions = compactThirdOrderDefinitions(result)
  const runtimeSource = serializeThirdOrderDefinitions(runtimeDefinitions)
  const definitions = {
    ...result,
    cells: result.cells.map((cell) => ({
      ...cell,
      versions: cell.versions.map((version) => ({
        version: version.version,
        recipe: version.representative.recipe,
        alignmentErrorBound: version.representative.alignmentErrorBound,
        duplicateCount: version.equivalentCandidates.length,
        query: version.query,
      })),
    })),
  }
  const counts = ['anti/anti', 'anti/spin', 'spin/anti', 'spin/spin'].map((label) => {
    const cells = result.cells.filter((cell) => `${cell.hand}/${cell.prop}` === label)
    return {
      label,
      populated: cells.filter((cell) => cell.versions.length).length,
      total: cells.length,
      patterns: cells.reduce((n, cell) => n + cell.versions.length, 0),
      maxVersions: Math.max(...cells.map((cell) => cell.versions.length)),
    }
  })
  const report = [
    '# Third Order generator review',
    '',
    'Generated by `npm run generate:third-order`. Discovery evidence for the compact definitions used by the Concepts page.',
    '',
    'The compact catalog publishes two versions per cell (1,088 entries). For 1:1 / 1:1 Spin / Spin, only the reviewed V1 and V4 are published as Versions 1 and 2. This report and the review links retain all four discoveries for that cell.',
    '',
    `Scans both timing orders, VTG cells ${result.scope.references.join(', ')} and their supported Spin/Anti variants, Swap, floor-plane 180, and Adjust 0 through 315 in 45-degree steps. Warp direction follows the final Hand category: Anti requires Anti; Spin requires Pro. No recent UI rotation exceptions are applied.`,
    '',
    'Hand/Prop labels follow the final ordered VTG tooltip spin classifier AFTER Swap. Recipes separately retain physical driver/follower indices after Swap, so scale/warp roles are not confused with tooltip ordering.',
    '',
    'Alignment uses ideal head radius 0.5 in hand-radius units. Actual head models use 0.48 and may have a small visual gap. Static presentation spacing and colors do not distinguish patterns.',
    '',
    'Equivalence preserves simultaneous hand positions and prop directions, allowing global rotation, turning the plane over, prop exchange, and any cycle starting point. Independent prop rotations and time reversal are not allowed.',
    '',
    'The analytic comparison handles uniform planar periodic motion. Unsupported shapes fail generation rather than being silently accepted. No finite-sample equivalence heuristic is used.',
    '',
    '| Hand / Prop | Populated cells | Unique definitions | Maximum versions per cell |',
    '| --- | --- | --- | --- |',
    ...counts.map(
      (c) => `| ${c.label} | ${c.populated}/${c.total} | ${c.patterns} | ${c.maxVersions} |`,
    ),
    '',
    'Counts are per timing cell and direction combination, not a global count across all timings.',
    '',
    '## Statistics',
    '',
    '```json',
    JSON.stringify(result.stats, null, 2),
    '```',
    '',
    '## Cell counts',
    '',
    '| Top timing | Left timing | Hand | Prop | Versions |',
    '| --- | --- | --- | --- | --- |',
    ...result.cells.map(
      (c) => `| ${c.handRatio} | ${c.propRatio} | ${c.hand} | ${c.prop} | ${c.versions.length} |`,
    ),
    '',
    `Runtime definitions: src/features/third-order/data/generatedDefinitions.ts (${Buffer.byteLength(runtimeSource)} bytes, ${runtimeDefinitions.recipes.length} shared recipes, ${runtimeDefinitions.versionSets.length} shared version lists). Every runtime recipe was checked against the complete generated animation before export.`,
    '',
    'Open review.html for playable links. catalog-review.json contains expanded recipes and URLs for review only; evidence.json retains all equivalent candidates and canonical transforms. Neither belongs in the app bundle. Version numbers are local to a cell and may change when rules change.',
    '',
  ].join('\n')
  const rows = definitions.cells
    .map(
      (cell) =>
        `<tr><td>${cell.handRatio}</td><td>${cell.propRatio}</td><td>${cell.hand} / ${cell.prop}</td><td>${cell.versions.map((v) => `<a href="http://localhost:8080/play-vtg?${v.query.replaceAll('&', '&amp;')}" target="_blank" rel="noopener">V${v.version}</a> <small>(${v.recipe.selection.reference}, ${v.recipe.selection.speedRatio}, Adjust ${v.recipe.thirdOrder.initial}, ${v.recipe.thirdOrder.timing}, ${v.recipe.timingOrder}${v.recipe.selection.swapProps ? ', Swap' : ''}, driver ${v.recipe.driverIndex + 1})</small>`).join('<br>') || 'No aligned candidate'}</td></tr>`,
    )
    .join('\n')
  const html = `<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width"><title>Third Order generator review</title><style>body{font:16px system-ui;margin:2rem}table{border-collapse:collapse}td,th{border:1px solid #aaa;padding:.5rem;text-align:left}small{color:#555}a{display:inline-block;margin:.25rem}</style><h1>Third Order generator review</h1><p>Discovery evidence for the Concepts catalog. The 1:1 / 1:1 Spin / Spin cell publishes only V1 and V4, as Versions 1 and 2; all discoveries remain here for review. Links open your local app on port 8080. See report.md for scope and equivalence rules.</p><table><thead><tr><th>Top</th><th>Left</th><th>Hand / Prop</th><th>Unique versions</th></tr></thead><tbody>${rows}</tbody></table></html>`
  await mkdir(outputDirectory, { recursive: true })
  await Promise.all([
    writeFile(
      path.join(outputDirectory, 'catalog-review.json'),
      JSON.stringify(definitions, null, 2) + '\n',
    ),
    writeFile(path.join(outputDirectory, 'evidence.json'), JSON.stringify(result, null, 2) + '\n'),
    writeFile(path.join(outputDirectory, 'report.md'), report),
    writeFile(path.join(outputDirectory, 'review.html'), html),
    writeFile(runtimePath, runtimeSource),
  ])
  console.log(
    JSON.stringify(
      {
        outputDirectory,
        runtimePath,
        runtimeBytes: Buffer.byteLength(runtimeSource),
        counts,
        ...result.stats,
      },
      null,
      2,
    ),
  )
} finally {
  await server.close()
}
